"""Generate the SRAG data dictionary from the two authoritative sources.

Neither source alone is enough:

  * the Ministry's PDF (``dicionario-de-dados-2019-a-2025.pdf``) defines the
    fields and their coded values, but it documents a *form*, not the file
    that is actually published — it names fields the data does not carry, and
    misses fields the data does;
  * the parquet files are the ground truth for which columns exist, but carry
    no descriptions.

So the dictionary is generated by anchoring the PDF's text on the real column
names, and every field is annotated with its measured fill rate per year. The
fill rates come from parquet column statistics (null counts in the file
metadata), not from reading the data, so this is cheap and exact.

Where the two disagree, the parquet wins and the disagreement is reported.

Usage:  python3 tools/build_srag_dictionary.py [data_dir] [output.md]
        (defaults: ~/Documents/srag-data, modules/00-dataset/DICTIONARY.md)
"""

