"""Publish aggregate evidence from the frozen full-training course study.

The export never includes per-record outcomes, predictions or model binaries.
Scientific plots are generated by the module notebooks from this projection.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import srag_51_course_study as C


def _verify_trial(directory: Path, spec: dict, result: dict) -> None:
    for key in ("family", "strategy", "params"):
        if C.canonical_bytes(result[key]) != C.canonical_bytes(spec[key]):
            raise ValueError(f"Candidate configuration differs from protocol: {key}")
    prediction = result["validation_predictions"]
    path = (directory / prediction["path"]).resolve()
    if directory not in path.parents:
        raise ValueError("Validation predictions must remain in the study directory")
    if C.file_hash(path) != prediction["sha256"]:
        raise ValueError("Validation prediction checkpoint integrity failure")
    with np.load(path, allow_pickle=False) as saved:
        recomputed = C.compute_metrics(saved["y"], saved["p"])
    if C.object_hash(recomputed) != C.object_hash(result["validation"]):
        raise ValueError("Recorded metrics differ from saved validation predictions")


def project_study(directory: Path) -> dict:
    """Read every completed validation trial; expose selection only if frozen."""
    directory = C.external_directory(directory)
    protocol = C.read_json(directory / "protocol.json")
    if (
        C.object_hash(
            {key: value for key, value in protocol.items() if key != "protocol_sha256"}
        )
        != protocol["protocol_sha256"]
    ):
        raise ValueError("Protocol integrity failure")
    trials = []
    for spec in protocol["candidates"]:
        result = C._completed(directory, protocol, spec)
        if result is not None:
            _verify_trial(directory, spec, result)
            trials.append(result)
    selection = None
    evaluation = None
    if (directory / "selection.json").exists():
        selection = C.read_json(directory / "selection.json")
        digest = C.object_hash(
            {
                key: value
                for key, value in selection.items()
                if key != "selection_sha256"
            }
        )
        if digest != selection["selection_sha256"]:
            raise ValueError("Selection integrity failure")
        if selection["protocol_sha256"] != protocol["protocol_sha256"]:
            raise ValueError("Selection belongs to another frozen protocol")
        if len(trials) != len(protocol["candidates"]):
            raise ValueError("A selected study cannot have incomplete candidates")
        winner = min(
            trials,
            key=lambda row: (row["validation"]["logloss"], row["candidate_id"]),
        )
        if winner["candidate_id"] != selection["winner"]["candidate_id"]:
            raise ValueError("Selected winner differs from validation minimum")
        model = selection["canonical_model"]
        if C.file_hash(directory / model["path"]) != model["sha256"]:
            raise ValueError("Canonical fitted model integrity failure")
    if (directory / "test-evaluation.json").exists():
        evaluation = C.read_json(directory / "test-evaluation.json")
        if (
            selection is None
            or evaluation["selection_sha256"] != selection["selection_sha256"]
            or evaluation["protocol_sha256"] != protocol["protocol_sha256"]
            or evaluation["canonical_model"] != selection["canonical_model"]
        ):
            raise ValueError("Evaluation does not belong to the frozen selection")
        if evaluation["selection_changed"]:
            raise ValueError("Selection cannot change after temporal evaluation")
        path = directory / "test-predictions.npz"
        if C.file_hash(path) != evaluation["test_predictions_sha256"]:
            raise ValueError("Temporal test prediction checkpoint integrity failure")
        with np.load(path, allow_pickle=False) as saved:
            recomputed = C.compute_metrics(saved["y"], saved["p"])
        if C.object_hash(recomputed) != C.object_hash(evaluation["test"]):
            raise ValueError("Recorded test metrics differ from saved predictions")
        if recomputed["n"] != protocol["splits"]["test"]["n"]:
            raise ValueError("Temporal test size differs from the frozen protocol")
    execution = None
    execution_path = directory / "followthrough-status.json"
    if execution_path.exists():
        local_status = C.read_json(execution_path)
        if local_status.get("stage") == "stopped-by-user":
            execution = {
                "stage": "stopped-by-user",
                "reason": local_status.get("reason", "User stopped the execution"),
                "checkpoints_preserved": True,
            }
    status = "complete" if evaluation else "selected" if selection else "running"
    if execution and selection is None:
        status = "stopped"
    return {
        "status": status,
        "execution": execution,
        "adoption": "Explanatory modules require explicit recomputation before adopting this predictor.",
        "protocol": protocol,
        "validation_candidates": trials,
        "selection": selection,
        "evaluation": evaluation,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--study-dir", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    evidence = project_study(args.study_dir)
    C.write_json(args.output, evidence)
    print(
        f"Aggregate study evidence: {evidence['status']}; "
        f"{len(evidence['validation_candidates'])}/{len(evidence['protocol']['candidates'])} "
        "completed validation candidates."
    )


if __name__ == "__main__":
    main()
